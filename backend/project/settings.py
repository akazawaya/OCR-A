def env_bool(name, default=False):
    if name not in os.environ:
        return default
    value = os.environ[name]
    if value == "":
        return default
    normalized = value.strip()
    if normalized == "true":
        return True
    if normalized == "false":
        return False
    raise ValueError(f"{name} must be 'true' or 'false', got {value!r}")


